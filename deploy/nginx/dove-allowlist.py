#!/usr/bin/env python3
"""Writes an nginx/Angie `geo` block that lets only Claude's and ChatGPT's servers (plus addresses you add) reach
Dove's machine endpoints (/mcp, OAuth token/register/revoke, metadata). See docs/deployment.md, "Restrict to Claude
and ChatGPT".

Usage (as root, from a systemd timer):
    dove-allowlist.py --out /etc/angie/dove_allow.conf [--extra /etc/dove/allow-extra.txt] \
        [--test 'angie -t' --reload 'systemctl reload angie']

- Anthropic publishes stable outbound ranges (https://platform.claude.com/docs/en/api/ip-addresses); they are listed
  below and change rarely. OpenAI publishes https://openai.com/chatgpt-connectors.json and asks integrators to refresh
  it regularly; it is fetched on every run.
- Every prefix is validated; implausibly wide prefixes are refused, so a broken or hostile answer cannot open the
  endpoints to everyone. On any error the previous file stays in place and the script exits non-zero.
- An IP allowlist only says "this request comes from Anthropic's or OpenAI's network". Dove's tokens, grants and
  invitations remain the actual authentication.
"""

import argparse
import ipaddress
import json
import os
import shlex
import subprocess
import sys
import tempfile
import urllib.request

# Anthropic outbound ranges (MCP tool calls), as published on 2026-11-13.
ANTHROPIC = ["160.79.104.0/21", "153.61.208.0/20"]
OPENAI_URL = "https://openai.com/chatgpt-connectors.json"
# Refuse anything wider than this: a provider egress block is never a /8.
MIN_PREFIX = {4: 12, 6: 24}
MAX_ENTRIES = 5000


def parse(prefix: str, source: str) -> str:
    net = ipaddress.ip_network(prefix.strip(), strict=False)
    if net.prefixlen < MIN_PREFIX[net.version]:
        raise ValueError(f"{source}: prefix {net} is implausibly wide")
    if net.is_private or net.is_loopback or net.is_link_local or net.is_multicast or net.is_unspecified:
        if source != "extra":
            raise ValueError(f"{source}: prefix {net} is not a public address range")
    return str(net)


def openai_prefixes(timeout: float) -> list:
    req = urllib.request.Request(OPENAI_URL, headers={"User-Agent": "dove-allowlist"})
    with urllib.request.urlopen(req, timeout=timeout) as r:  # noqa: S310 (fixed https URL)
        if r.status != 200:
            raise ValueError(f"openai: HTTP {r.status}")
        doc = json.loads(r.read(2_000_000))
    out = []
    for p in doc.get("prefixes", []):
        v = p.get("ipv4Prefix") or p.get("ipv6Prefix")
        if v:
            out.append(parse(v, "openai"))
    if not out:
        raise ValueError("openai: no prefixes in the published list")
    return out


def extra_prefixes(path: str) -> list:
    out = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if line:
                out.append(parse(line, "extra"))
    return out


def render(groups: dict) -> str:
    lines = [
        "# Generated by dove-allowlist.py; do not edit (it is rewritten on every run).",
        "geo $dove_ip_ok {",
        "    default 0;",
    ]
    seen = set()
    for name, prefixes in groups.items():
        lines.append(f"    # {name}")
        for p in prefixes:
            if p not in seen:
                seen.add(p)
                lines.append(f"    {p} 1;")
    lines.append("}")
    if len(seen) > MAX_ENTRIES:
        raise ValueError(f"{len(seen)} prefixes is more than the {MAX_ENTRIES} allowed")
    return "\n".join(lines) + "\n"


def run(cmd: str) -> None:
    subprocess.run(shlex.split(cmd), check=True, stdout=subprocess.DEVNULL)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out", required=True)
    ap.add_argument("--extra", help="file with one extra CIDR per line (your own addresses)")
    ap.add_argument("--no-openai", action="store_true", help="allow Claude only")
    ap.add_argument("--test", help="config test command, for example 'angie -t'")
    ap.add_argument("--reload", help="reload command, for example 'systemctl reload angie'")
    ap.add_argument("--timeout", type=float, default=20)
    a = ap.parse_args()

    groups = {"Anthropic (Claude) outbound": [parse(p, "anthropic") for p in ANTHROPIC]}
    if not a.no_openai:
        groups["OpenAI (ChatGPT connectors)"] = openai_prefixes(a.timeout)
    if a.extra and os.path.exists(a.extra):
        groups["extra"] = extra_prefixes(a.extra)
    text = render(groups)

    try:
        with open(a.out, encoding="utf-8") as f:
            old = f.read()
    except FileNotFoundError:
        old = None
    if old == text:
        return 0

    d = os.path.dirname(os.path.abspath(a.out))
    fd, tmp = tempfile.mkstemp(dir=d, prefix=".dove_allow.")
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(text)
    os.chmod(tmp, 0o644)
    os.replace(tmp, a.out)
    try:
        if a.test:
            run(a.test)
        if a.reload:
            run(a.reload)
    except subprocess.CalledProcessError:
        if old is not None:
            with open(a.out, "w", encoding="utf-8") as f:
                f.write(old)
        else:
            os.unlink(a.out)
        print("config test or reload failed; the previous allowlist was restored", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except Exception as e:  # noqa: BLE001 (report and keep the old file)
        print(f"dove-allowlist: {e}", file=sys.stderr)
        sys.exit(1)
